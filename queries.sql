#Calculate the total sales revenue for each month. Then, use a window function (LAG) to show the previous month's revenue and find the percentage growth or drop from month to month

select month(rs.SaleDate) as date,sum(totalamount) from retail_sales rs 
GROUP by date

WITH MonthlySales AS (
    select 
    month(rs.SaleDate) as months,
    sum(totalamount) as spent from retail_sales rs 
    GROUP by months 
)
SELECT 
    months,
    spent,
    LAG(spent) OVER (ORDER BY months) AS PrevRev,
    ROUND(((spent - LAG(spent) OVER (ORDER BY months)) / LAG(spent) OVER (ORDER BY months)) * 100, 2) AS GrowthPct
FROM MonthlySales;



