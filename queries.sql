 #Find out how many days pass between a customer's first purchase and their second purchase
    
WITH OrderDates AS (
    SELECT 
        customerid,
        saledate AS first_order_date,
        LEAD(saledate, 1) OVER (PARTITION BY customerid ORDER BY saledate) AS second_order_date
    FROM retail_sales
)
SELECT 
    customerid,
    first_order_date,
    second_order_date,
    DATEDIFF(second_order_date, first_order_date) AS days_between_orders
FROM OrderDates
WHERE second_order_date IS NOT NULL;

